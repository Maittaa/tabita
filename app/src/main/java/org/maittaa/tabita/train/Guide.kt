    fun find(name: String): ExerciseInfo? {
        val n = norm(name)
        return all.firstOrNull { norm(it.name) == n || it.aliases.any { a -> norm(a) == n } }
            ?: all.firstOrNull { n.startsWith(norm(it.name)) }
    }

